"""Turn seed/companies.csv into db/002_seed.sql.

The CSV is the file you maintain by hand. Run this after editing it:
    python3 scripts/make_seed_sql.py
Then paste db/002_seed.sql into the Supabase SQL editor.
"""
import csv
import pathlib
import yaml

root = pathlib.Path(__file__).resolve().parent.parent
excluded = {n.strip().lower() for n in
            yaml.safe_load((root / "config/config.yaml").read_text())["excluded_companies"]}


def lit(value):
    """SQL string literal, or null for an empty value."""
    if value is None or value.strip() == "":
        return "null"
    return "'" + value.strip().replace("'", "''") + "'"


rows, skipped = [], []
with open(root / "seed/companies.csv", newline="", encoding="utf-8") as f:
    for r in csv.DictReader(f):
        name = (r["name"] or "").strip()
        if not name:
            continue
        if name.lower() in excluded:
            skipped.append(name)
            continue
        tags = [t.strip() for t in (r["source_tags"] or "").split(";") if t.strip()]
        tag_sql = "array[" + ",".join(lit(t) for t in tags) + "]::text[]"
        rows.append(f"  ({lit(name)}, {lit(r['domain'])}, {lit(r['tier'] or 'seed')}, "
                    f"{tag_sql}, false)")

sql = f"""-- Generated by scripts/make_seed_sql.py from seed/companies.csv. Do not edit by hand.
-- Safe to run more than once. Re-running merges source tags and keeps your fixes.

-- 1. Starter list ({len(rows)} companies). Every row starts as verified = false.
insert into watch_company (name, domain, tier, source_tags, verified) values
{",\n".join(rows)}
on conflict (lower(regexp_replace(name, '\\s+', '', 'g'))) do update
  set source_tags = (select array_agg(distinct t)
                     from unnest(watch_company.source_tags || excluded.source_tags) t),
      domain = coalesce(watch_company.domain, excluded.domain);

-- 2. India tier, copied from your existing "company" table.
insert into watch_company (name, domain, tier, source_tags, verified)
select name, domain, 'india', array['india']::text[], false
from (
  select distinct on (lower(regexp_replace(name, '\\s+', '', 'g')))
         btrim(name) as name, nullif(btrim(domain), '') as domain
  from company
  where name is not null and btrim(name) <> ''
  order by lower(regexp_replace(name, '\\s+', '', 'g')),
           (nullif(btrim(domain), '') is null)
) c
on conflict (lower(regexp_replace(name, '\\s+', '', 'g'))) do update
  set source_tags = (select array_agg(distinct t)
                     from unnest(watch_company.source_tags || excluded.source_tags) t),
      domain = coalesce(watch_company.domain, excluded.domain);

-- 3. Result. Check these numbers.
select tier, count(*) as companies,
       count(*) filter (where domain is null) as without_domain
from watch_company group by tier order by tier;
"""
(root / "db/002_seed.sql").write_text(sql, encoding="utf-8")
print(f"wrote db/002_seed.sql: {len(rows)} starter rows, skipped excluded: {skipped or 'none'}")
